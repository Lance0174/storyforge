作者明确要求的改动只作用于指定范围；未授权的姓名、数字、否定、因果、时间顺序、人物知识、关系和结局保持原样。设定冲突只指出会影响本任务的部分，不擅自裁决。规划中的新设想是待选方案，不伪装成已确认事实。
