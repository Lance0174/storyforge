interface CraftSpec {
  id: string
  moduleKey: PromptModuleKey
  name: string
  description: string
  task: string
  inputLabel: string
  placeholder: string
  optionalInput?: boolean
  example?: { before: string; after: string; note: string }
}

function craft(spec: CraftSpec): PromptSeed {
  return {
    scope: 'system',
    assetId: `CRAFT-${spec.id}`,
    moduleKey: spec.moduleKey,
    promptType: spec.moduleKey === 'chapter.de-ai' ? 'edit' : 'craft',
    name: `熔炉工坊｜${spec.name}`,
    description: `${spec.description} 输入：${spec.inputLabel}；其余要求可留空。可在工作流选择此模板并填写材料，也可复制后自定义。`,
    systemPrompt: CRAFT_SYSTEM,
    userPromptTemplate: `${spec.task}\n\n【本次材料：${spec.inputLabel}】\n{{text}}\n{{#if userHint}}\n【作者本次要求与不可改动项】\n{{userHint}}\n{{/if}}`,
    variables: ['text', 'userHint'],
    variableBindings: [{
      variable: 'text', label: spec.inputLabel, manual: true,
      required: !spec.optionalInput, placeholder: spec.placeholder,
    }],
    isActive: false,
    ...(spec.example ? {
      examples: {
        good: [{
          id: `CRAFT-${spec.id}-example`, source: 'system' as const, createdAt: 1790467200000,
          text: `方法示例（非本次素材）\n原句：${spec.example.before}\n处理后：${spec.example.after}\n取舍：${spec.example.note}`,
          note: '熔炉原创示例；只迁移方法，不复制内容。',
        }],
      },
    } : {}),
  }
}

